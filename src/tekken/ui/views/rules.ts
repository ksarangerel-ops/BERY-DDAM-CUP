function block(b: Block): string {
  if ('p' in b) return `<p>${esc(b.p)}</p>`;
  if ('h' in b) return `<h3>${esc(b.h)}</h3>`;
  if ('ul' in b) return `<ul>${b.ul.map(li => `<li>${esc(li)}</li>`).join('')}</ul>`;
  return `<div class="table-wrap"><table class="rules-table"><tbody>${b.table.map(([k, v]) => `<tr><th>${esc(k)}</th><td>${esc(v)}</td></tr>`).join('')}</tbody></table></div>`;
}

